let successCount = 0;
for (const [lang, data] of Object.entries(T)) {
  const filePath = resolve(LOCALES, FILE_MAP[lang]);
  let json;
  try {
    json = JSON.parse(readFileSync(filePath, 'utf8'));
  } catch (e) {
    console.error(`FAILED to parse ${FILE_MAP[lang]}: ${e.message}`);
    continue;
  }

  // Fix/add tabs keys
  const tabs = json.tour_config.tabs;
  tabs.tour_builder = data.tabs.tour_builder;
  tabs.business     = data.tabs.business;
  tabs.suppliers    = data.tabs.suppliers;
  tabs.team         = data.tabs.team;
  tabs.inbox        = data.tabs.inbox;

  // Add top-level sections (overwrite if already exists)
  json.suppliers = data.suppliers;
  json.team      = data.team;
  json.inbox     = data.inbox;

  try {
    writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
    console.log(`✓ ${FILE_MAP[lang]}`);
    successCount++;
  } catch (e) {
    console.error(`FAILED to write ${FILE_MAP[lang]}: ${e.message}`);
  }
}

console.log(`\nDone: ${successCount}/11 locale files updated.`);
